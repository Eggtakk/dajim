def flatten_brands():
    """{정규화된 브랜드 문자열: 카테고리} 형태로 펼친다."""
    out = {}
    for cat, names in BRANDS.items():
        for n in names:
            key = n.replace(" ", "").lower()
            out[key] = cat
    return out


def split_brands():
    """부분매칭용(3글자 이상)과 정확일치용(2글자)으로 나눈다.

    '멜론', '쏘카', '타다' 같은 2글자 브랜드를 부분매칭하면
    '멜론카페', '쏘카페' 같은 상호에 오탐이 난다.
    그렇다고 빼면 실제 결제 표기 '(주)멜론'을 놓친다. 정확일치로만 인정한다.
    """
    flat = flatten_brands()
    partial = {k: v for k, v in flat.items() if len(k) >= 3}
    exact = {k: v for k, v in flat.items() if len(k) == 2}
    exact.update(EXACT_BRANDS)
    return partial, exact


